#!/usr/bin/env python3
"""Writes locales/locales.js from locales/locales.json (the one source of the game's words), and locales/voices.js,
the index of each language's own voice-over (assets/VO-<LANG>/manifest.json, written by tools/voice-elevenlabs.py).

Every page loads locales/locales.js (window.LOCALES) as a plain script, so the words are there before any game
script runs, from a server or from disk alike (shell/i18n.js). Run this after every edit to the JSON:

    python3 tools/build-locales.py           write locales/locales.js
    python3 tools/build-locales.py --check   only say whether locales/locales.js is up to date (exit 1 if not)

It also checks the file: every language has exactly the keys "en" has, every value is text, and each translation
keeps its English line's {placeholders}, *stressed* words and line breaks. And the voice-over: every clip is there,
names a key the file has, and was recorded from the line as it is now (a line edited since needs recording again).
"""
import glob
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'locales', 'locales.json')
OUT = os.path.join(ROOT, 'locales', 'locales.js')
META = {'defaultLanguage', 'languageLabels', 'supportedLanguages'}
HEAD = ('// GENERATED by tools/build-locales.py from locales/locales.json - do not edit by hand: edit the JSON,\n'
        '// then run python3 tools/build-locales.py. Read by shell/i18n.js.\n')
VOICES_OUT = os.path.join(ROOT, 'locales', 'voices.js')
VOICES_HEAD = ('// GENERATED by tools/build-locales.py from assets/VO-<LANG>/manifest.json - do not edit by hand.\n'
               '// Each language\'s own voice-over: its folder, and per clip [key, who says it, seconds, the line on\n'
               '// screen, where each corner letter is said (share of the line) or 0]. Read by shell/i18n.js.\n')


def voices(data):
    """locales/voices.js and what is wrong with the recordings"""
    out, issues = {}, []
    for path in sorted(glob.glob(os.path.join(ROOT, 'assets', 'VO-*', 'manifest.json'))):
        folder = os.path.dirname(path)
        rel = os.path.relpath(folder, ROOT).replace(os.sep, '/') + '/'
        with open(path, encoding='utf-8') as f:
            man = json.load(f)
        lang, table, clips = man.get('language'), data.get(man.get('language')), []
        if not isinstance(table, dict):
            issues.append(f'{rel}: no "{lang}" in locales.json')
            continue
        if man.get('missing'):  # part-recorded (a test, or a run that stopped): the game keeps the English voice
            issues.append(f'{rel}: {man["missing"]} clips not recorded yet (tools/voice-elevenlabs.py --lang {lang}); '
                          f'"{lang}" is left out of locales/voices.js until they are')
            continue
        exts = {c['file'].rsplit('.', 1)[1] for c in man['clips']}  # one format per language (shell/i18n.js: V.ext)
        if len(exts) != 1:
            issues.append(f'{rel}: clips in {len(exts)} formats ({", ".join(sorted(exts))}); the game reads one per language')
            continue
        for c in man['clips']:
            name = c['file'].rsplit('.', 1)[0]
            if not os.path.exists(os.path.join(folder, c['file'])):
                issues.append(f'{rel}{c["file"]}: missing')
            if c['key'] not in table:
                issues.append(f'{rel}{c["file"]}: no key "{c["key"]}" in locales.json')
            elif 'variant' not in c and c['text'] != table[c['key']]:
                issues.append(f'{rel}{c["file"]}: "{c["key"]}" changed since it was recorded: record it again '
                              '(tools/voice-elevenlabs.py)')
            clips.append([name, c['speaker'], c['seconds'], c['text'], c.get('letters') or 0])
        out[lang] = {'dir': rel, 'ext': exts.pop(), 'clips': clips}
    text = (VOICES_HEAD + 'window.LOCALE_VOICES = {\n' + ',\n'.join(
        f'  {json.dumps(lang)}: {{ "dir": {json.dumps(v["dir"])}, "ext": {json.dumps(v["ext"])}, "clips": [\n' +
        ',\n'.join('    ' + json.dumps(c, ensure_ascii=False) for c in v['clips']) + '\n  ] }'
        for lang, v in out.items()) + '\n};\n')
    return text, issues, out


def problems(data):
    out = []
    en = data.get('en')
    if not isinstance(en, dict) or not en:
        return ['no "en" object']
    for key, val in en.items():
        if not isinstance(val, str):
            out.append(f'en.{key}: not text')
    for lang, table in data.items():
        if lang in META or lang == 'en':
            continue
        if not isinstance(table, dict):
            out.append(f'{lang}: not an object')
            continue
        missing = [k for k in en if k not in table]
        extra = [k for k in table if k not in en]
        if missing:
            out.append(f'{lang}: missing {", ".join(missing)}')
        if extra:
            out.append(f'{lang}: not in "en": {", ".join(extra)}')
        for key, val in table.items():
            if key not in en:
                continue
            if not isinstance(val, str):
                out.append(f'{lang}.{key}: not text')
                continue
            src = en[key]
            if sorted(re.findall(r'\{\w+\}', src)) != sorted(re.findall(r'\{\w+\}', val)):
                out.append(f'{lang}.{key}: placeholders differ from English')
            if ('*' in src) != ('*' in val) or val.count('*') % 2:
                out.append(f'{lang}.{key}: *stressed* words differ from English')
            if src.count('\n') and not val.count('\n'):
                out.append(f'{lang}.{key}: English has line breaks (\\n), this has none')
    return out


def main():
    with open(SRC, encoding='utf-8') as f:
        data = json.load(f)
    issues = problems(data)
    for line in issues:
        print('locales.json:', line)
    vtext, vissues, vo = voices(data)
    for line in vissues:
        print('voice-over:', line)
    issues += vissues
    text = HEAD + 'window.LOCALES = ' + json.dumps(data, ensure_ascii=False, indent=2) + ';\n'
    if '--check' in sys.argv[1:]:
        same = True
        for path, want, name in ((OUT, text, 'locales/locales.js'), (VOICES_OUT, vtext, 'locales/voices.js')):
            try:
                with open(path, encoding='utf-8') as f:
                    ok = f.read() == want
            except FileNotFoundError:
                ok = False
            same = same and ok
            print(f'{name} is up to date' if ok else f'{name} is OUT OF DATE: run python3 tools/build-locales.py')
        sys.exit(0 if same and not issues else 1)
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write(text)
    with open(VOICES_OUT, 'w', encoding='utf-8') as f:
        f.write(vtext)
    print(f'wrote locales/locales.js ({len(data["en"])} keys; languages: {", ".join(k for k in data if k not in META)})')
    print('wrote locales/voices.js (' + (', '.join(f'{k}: {len(v["clips"])} clips' for k, v in vo.items()) or 'no voice-over yet') + ')')
    sys.exit(1 if issues else 0)


if __name__ == '__main__':
    main()

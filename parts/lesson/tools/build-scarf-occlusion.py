"""Read the original wing paint to register foreground occlusion (no art edits).

Python 3 + Pillow. Packed rectangles use 256-unit cell coordinates. The renderer
restores the original wing/hand pixels above the scarf, including moving wings.
"""
import base64
import json
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
manifest = json.loads((ROOT / 'js/swiftee-manifest.js').read_text().split('window.SWIFTEE_MANIFEST = ')[1].rstrip(';\n'))


def mask(frame):
    frame = frame.resize((256, 256)).convert('RGBA')
    pixels = list(frame.getdata())
    rectangles, active = [], {}
    for y in range(256):
        spans, start = [], None
        for x in range(257):
            r, g, b, a = pixels[y * 256 + min(x, 255)]
            # The dark teal foreground wing paint differs from the lighter
            # turquoise torso. Cream eyes, red beak and yellow tools are excluded.
            wing = x < 256 and a > 220 and r < 45 and 110 < g < 166 and 105 < b < 163 and g - r > 85
            if wing and start is None:
                start = x
            if not wing and start is not None:
                if x - start > 1:
                    spans.append((start, x - start))
                start = None
        following = {}
        for span in spans:
            rect = active.pop(span, [span[0], y, span[1], 0])
            rect[3] += 1
            following[span] = rect
        rectangles.extend(active.values())
        active = following
    rectangles.extend(active.values())
    return base64.b64encode(bytes(v for rect in rectangles for v in rect)).decode()


def sheet(path, cell, cols, count):
    im = Image.open(path).convert('RGBA')
    return [mask(im.crop(((i % cols) * cell, (i // cols) * cell,
                          (i % cols + 1) * cell, (i // cols + 1) * cell))) for i in range(count)]


out = {name: sheet(ROOT / 'swiftee-assets' / s['image'], s['cell'], s['cols'], s['frames'])
       for name, s in manifest['scales']['1x']['sheets'].items()}
out['protractor'] = sheet(ROOT / 'assets/images/swiftee-protractor.webp', 896, 4, 8)
pool = list(dict.fromkeys(packed for frames in out.values() for packed in frames))
indices = {packed: i for i, packed in enumerate(pool)}
data = {'masks': pool, 'frames': {name: [indices[packed] for packed in frames] for name, frames in out.items()}}
(ROOT / 'js/scarf-occlusion.js').write_text('// GENERATED by tools/build-scarf-occlusion.py.\nwindow.SWIFTEE_SCARF_OCCLUSION = ' + json.dumps(data, separators=(',', ':')) + ';\n')
print('Registered foreground wings for', sum(map(len, out.values())), 'frames.')

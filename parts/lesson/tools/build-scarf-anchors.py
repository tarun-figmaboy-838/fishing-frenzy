"""Register the generated scarf to every original pose; never modifies source art.

Run with Python 3 + Pillow after rebuilding the Swiftee manifest. Coordinates
are fractions of the original cell, shared by the 1x and 2x renderers.
"""
import json
import math
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
manifest = json.loads((ROOT / 'js/swiftee-manifest.js').read_text().split('window.SWIFTEE_MANIFEST = ')[1].rstrip(';\n'))


def anchor(image):
    w, h = image.size
    # Mint cheek feathers, excluding turquoise wings, cream eyes and props.
    points = [(i % w, i // w) for i, (r, g, b, a) in enumerate(image.getdata())
              if a > 180 and 85 < r < 180 and g > 185
              and 1.35 * r < g < 2.05 * r and r + 25 < b < g - 12]
    if len(points) < 20:
        return None  # Fully offscreen/transparent frames must not gain a floating scarf.
    mx = sum(x for x, y in points) / len(points)
    my = sum(y for x, y in points) / len(points)
    xx = sum((x - mx) ** 2 for x, y in points)
    yy = sum((y - my) ** 2 for x, y in points)
    xy = sum((x - mx) * (y - my) for x, y in points)
    angle = max(-.65, min(.65, .5 * math.atan2(2 * xy, xx - yy)))
    co, si = math.cos(angle), math.sin(angle)
    horizontal = sorted((x - mx) * co + (y - my) * si for x, y in points)
    vertical = sorted(-(x - mx) * si + (y - my) * co for x, y in points)
    bottom = vertical[int(len(vertical) * .98)] + h * .012
    width = (horizontal[int(len(horizontal) * .99)] - horizontal[int(len(horizontal) * .01)]) * 1.18
    return [round((mx - bottom * si) / w, 5), round((my + bottom * co) / h, 5),
            round(width / w, 5), round(angle, 4)]


def frames(path, cell, cols, count):
    im = Image.open(path).convert('RGBA')
    assert im.width >= cols * cell and im.height >= math.ceil(count / cols) * cell, path
    result = []
    for i in range(count):
        pose = im.crop(((i % cols) * cell, (i // cols) * cell,
                        (i % cols + 1) * cell, (i // cols + 1) * cell))
        p = anchor(pose)
        if p and 'peeping' in str(path):
            # The full-height orange wall is in front of both bird and scarf.
            columns = [x for x in range(cell) if sum(
                1 for y in range(cell) for r, g, b, a in [pose.getpixel((x, y))]
                if a > 180 and r > 200 and 60 < g < 165 and b < 140) > cell * .7]
            if columns:
                p.append((max(columns) + 1) / cell)
        result.append(p)
    return result


out = {}
for name, sheet in manifest['scales']['1x']['sheets'].items():
    out[name] = frames(ROOT / 'swiftee-assets' / sheet['image'], sheet['cell'], sheet['cols'], sheet['frames'])
    # Rive's old transitions contain two translucent poses blended together.
    # Register between the clean endpoints instead of mistaking their union
    # (or a blended prop) for one oversized face. Talking is clean frame art.
    poses = out[name]
    transition = name.endswith(('_start', '_stop')) or name in ('callstart', 'callstop', 'daydreaming_stop', 'wake')
    if transition and not name.startswith(('talk_', 'peeping_')) and poses[0] and poses[-1]:
        first, last = poses[0], poses[-1]
        out[name] = [[round(a + (b - a) * i / (len(poses) - 1), 5)
                      for a, b in zip(first, last)] for i in range(len(poses))]
    if name == 'blinking':
        # Only the eyelids change here. Their cheek-mask covariance must not
        # make a fixed collar slide or rotate with each blink.
        out[name] = [poses[0][:] for _ in poses]
out['protractor'] = frames(ROOT / 'assets/images/swiftee-protractor.webp', 896, 4, 8)
for i in (5, 6):
    out['protractor'][i].extend([0, -1])  # left-facing poses: tail stays away from the instrument
out['still'] = [anchor(Image.open(ROOT / 'assets/images/swiftee.webp').convert('RGBA'))]
(ROOT / 'js/scarf-anchors.js').write_text('// GENERATED by tools/build-scarf-anchors.py.\nwindow.SWIFTEE_SCARF_ANCHORS = ' + json.dumps(out, separators=(',', ':')) + ';\n')
print(f'Registered {sum(map(len, out.values()))} frames across {len(out)} clips/images.')
print('Frames with no visible face:', {k: v.count(None) for k, v in out.items() if None in v})

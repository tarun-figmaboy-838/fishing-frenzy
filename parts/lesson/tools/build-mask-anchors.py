"""Registers the diving mask (js/dive-mask.js) to every pose: where Swiftee's eyes are in each frame. Never modifies
source art. For each frame it finds the two cream eye discs, splits them at the gap the beak leaves between them,
and records [cx, cy, spread, r, angle]: the midpoint between the eye centres, the distance between them and the mean
eye radius (fractions of the cell) and the tilt of the line through them. Frames with the eyes shut or turned away
borrow from the nearest good frame of the same clip, or else from the scarf anchor (js/scarf-anchors.js) with the
average eye offset. Run with a Python that has numpy and Pillow:
  ~/.cache/popo-voice311/bin/python tools/build-mask-anchors.py"""
import json, math
from pathlib import Path
import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
manifest = json.loads((ROOT / 'js/swiftee-manifest.js').read_text().split('window.SWIFTEE_MANIFEST = ')[1].rstrip(';\n'))
scarf = json.loads((ROOT / 'js/scarf-anchors.js').read_text().split('window.SWIFTEE_SCARF_ANCHORS = ')[1].rstrip(';\n'))

def eyes(cell_img):
    a = np.asarray(cell_img.convert('RGBA')).astype(np.int16)
    h, w = a.shape[:2]
    m = (a[..., 3] > 200) & (a[..., 0] > 225) & (a[..., 1] > 212) & (a[..., 2] > 180)
    if m.sum() < w * h * 0.0025: return None
    cols = m.sum(axis=0); xs = np.nonzero(cols)[0]
    x0, x1 = xs.min(), xs.max()
    # the widest run of empty columns between the two discs (the beak's gap)
    best, run, start, cut = 0, 0, None, None
    for x in range(x0, x1 + 1):
        if cols[x] == 0:
            if run == 0: start = x
            run += 1
            if run > best: best, cut = run, start + run // 2
        else: run = 0
    if not cut or best < 2: return None  # one disc (turned away) or merged: borrow
    out = []
    for lo, hi in ((x0, cut), (cut, x1 + 1)):
        sub = m[:, lo:hi]; n = sub.sum()
        if n < w * h * 0.001: return None
        ys, xs2 = np.nonzero(sub)
        out.append((xs2.mean() + lo, ys.mean(), math.sqrt(n / math.pi)))
    (lx, ly, lr), (rx, ry, rr) = out
    if min(lr, rr) < 0.45 * max(lr, rr): return None  # one disc mostly hidden: borrow
    return [round((lx + rx) / 2 / w, 5), round((ly + ry) / 2 / h, 5), round(math.hypot(rx - lx, ry - ly) / w, 5),
            round((lr + rr) / 2 / w, 5), round(math.atan2(ry - ly, rx - lx), 4)]

def frames(path, cell, cols, count):
    im = Image.open(path)
    return [eyes(im.crop(((i % cols) * cell, (i // cols) * cell, (i % cols + 1) * cell, (i // cols + 1) * cell))) for i in range(count)]

out = {}
for name, sheet in manifest['scales']['1x']['sheets'].items():
    out[name] = frames(ROOT / 'swiftee-assets' / sheet['image'], sheet['cell'], sheet['cols'], sheet['frames'])
out['protractor'] = frames(ROOT / 'assets/images/swiftee-protractor.webp', 896, 4, 8)
out['still'] = [eyes(Image.open(ROOT / 'assets/images/swiftee.webp'))]

# Blinks and squints shrink the visible eye discs (and move their centres): the mask must not shrink or bob with
# them. A frame whose eye size is under 82% of its clip's median is replaced by the nearest open-eyed frame; the
# blinking clip only moves its eyelids, so its mask stays where it is in frame 0.
for name, poses in out.items():
    rs = sorted(p[3] for p in poses if p)
    if not rs: continue
    med = rs[len(rs) // 2]
    for i, p in enumerate(poses):
        if p and p[3] < 0.82 * med: poses[i] = None
    if name == 'blinking' and poses[0]: out[name] = [poses[0][:] for _ in poses]

# the average eye offset from the scarf anchor, in scarf widths, in the scarf's own frame
offs = []
for name, poses in out.items():
    for i, p in enumerate(poses):
        s = (scarf.get(name) or [None] * (i + 1))[i] if name in scarf and i < len(scarf[name]) else None
        if p and s:
            dx, dy = p[0] - s[0], p[1] - s[1]; co, si = math.cos(-s[3]), math.sin(-s[3])
            offs.append(((dx * co - dy * si) / s[2], (dx * si + dy * co) / s[2], p[2] / s[2], p[3] / s[2]))
O = [sum(o[k] for o in offs) / len(offs) for k in range(4)]
filled = 0
for name, poses in out.items():
    good = [i for i, p in enumerate(poses) if p]
    for i, p in enumerate(poses):
        if p: continue
        if good:  # the nearest good frame of the same clip
            j = min(good, key=lambda g: abs(g - i)); poses[i] = poses[j][:]
        else:
            s = scarf.get(name, [None])[i] if name in scarf and i < len(scarf[name]) else None
            if s:
                co, si = math.cos(s[3]), math.sin(s[3]); ox, oy = O[0] * s[2], O[1] * s[2]
                poses[i] = [round(s[0] + ox * co - oy * si, 5), round(s[1] + ox * si + oy * co, 5), round(O[2] * s[2], 5), round(O[3] * s[2], 5), s[3]]
        filled += 1
(ROOT / 'js/mask-anchors.js').write_text('// GENERATED by tools/build-mask-anchors.py: Swiftee\'s eyes per frame, [cx, cy, spread, r, angle].\nwindow.SWIFTEE_MASK_ANCHORS = ' + json.dumps(out, separators=(',', ':')) + ';\n')
print(f'{sum(map(len, out.values()))} frames across {len(out)} clips; {filled} borrowed; still empty:', {k: v.count(None) for k, v in out.items() if None in v})
print('mean offset from scarf (widths):', [round(v, 3) for v in O], 'from', len(offs), 'frames')
